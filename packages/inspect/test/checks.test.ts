/**
 * Spec 007 acceptance 1: a passing and a failing fixture, generated by our own code, for each
 * check. Checks run straight from the registry over the document model; the profile evaluator
 * is not part of this package yet, so `inspect` below applies only param defaults and the
 * per-rule severity mapping.
 */

const registry = builtinRegistry();

async function inspect(bytes: Uint8Array, context: PreflightContext = {}, checks: Record<string, CheckConfig> = {}): Promise<Finding[]> {
  const doc = await loadDocumentModel(bytes, context);
  return registry.list().flatMap((check) => {
    const config = checks[check.id];
    const params = Value.Default(check.params, structuredClone(config?.params ?? {})) as Static<TObject>;
    expect(Value.Check(check.params, params), `${check.id} params`).toBe(true);
    return check.run(doc, params).flatMap((raw): Finding[] => {
      const severity = config?.severity?.[raw.rule] ?? check.rules[raw.rule]?.defaultSeverity;
      expect(severity, `${check.id}/${raw.rule} is a declared rule`).toBeDefined();
      if (severity === undefined || severity === "off") return [];
      return [
        {
          checkId: check.id,
          severity,
          ...(raw.page === undefined ? {} : { page: raw.page }),
          ...(raw.objectRef === undefined ? {} : { objectRef: raw.objectRef }),
          message: raw.message,
          data: { rule: raw.rule, ...raw.data },
        },
      ];
    });
  });
}

function of(findings: readonly Finding[], checkId: string): Finding[] {
  return findings.filter((f) => f.checkId === checkId);
}

function rules(findings: readonly Finding[]): [unknown, string][] {
  return findings.map((f) => [f.data.rule, f.severity]);
}

/** The single finding, failing the test when there is not exactly one. */
function only(findings: readonly Finding[]): Finding {
  expect(findings).toHaveLength(1);
  return findings[0] as Finding;
}

async function claims(bytes: Uint8Array) {
  return conformanceClaims(await loadDocumentModel(bytes));
}

describe("registry", () => {
  it("lists the built-in checks in report order, document first", () => {
    expect(registry.list().map((c) => c.id)).toEqual([
      "document",
      "page-boxes",
      "printable-width",
      "image-resolution",
      "fonts",
      "color-spaces",
      "transparency-overprint",
      "output-intent",
      "conformance",
    ]);
    expect(registry.has("fonts")).toBe(true);
    expect(registry.get("missing")).toBeUndefined();
  });

  it("rejects invalid and duplicate check ids", () => {
    const check = (id: string) => defineCheck({ id, title: id, description: id, rules: {}, params: Type.Object({}), run: () => [] });
    expect(() => new CheckRegistry([check("Bad Id")])).toThrow(TypeError);
    expect(() => new CheckRegistry([...BUILTIN_CHECKS, check("fonts")])).toThrow(/already registered/);
  });

  it("every check's default params are valid", () => {
    for (const check of registry.list()) {
      const params = Value.Default(check.params, {}) as Static<TObject>;
      expect(Value.Check(check.params, params), check.id).toBe(true);
      expect(check.validateParams?.(params) ?? [], check.id).toEqual([]);
    }
  });
});

describe("image-resolution", () => {
  it("a 72 ppi image placed at 200 % is an error", async () => {
    const findings = of(await inspect(await imageFixture({ widthPx: 72, heightPx: 72, placedWidthPt: 144, placedHeightPt: 144 })), "image-resolution");
    expect(rules(findings)).toEqual([["below-error-threshold", "error"]]);
    const finding = only(findings);
    expect(finding.data.ppi).toBeCloseTo(36, 9);
    expect(finding.page).toBe(0);
    expect(finding.objectRef).toMatch(/^\d+ 0 R$/);
  });

  it("a 72 ppi image scaled to 200 % by a job edit is an error", async () => {
    const bytes = await imageFixture({ widthPx: 72, heightPx: 72, placedWidthPt: 72, placedHeightPt: 72 });
    // Unscaled, 72 ppi is only below the warn threshold; the 200 % edit takes it below the error threshold.
    expect(rules(of(await inspect(bytes), "image-resolution"))).toEqual([["below-warn-threshold", "warn"]]);
    const finding = only(of(await inspect(bytes, { edits: [{ kind: "scale", percent: 200 }] }), "image-resolution"));
    expect(finding.severity).toBe("error");
    expect(finding.data.ppi).toBeCloseTo(36, 9);
    expect(finding.data.jobScale).toBeCloseTo(2, 12);
  });

  it("a 300 ppi image passes", async () => {
    const findings = await inspect(await imageFixture({ widthPx: 300, heightPx: 300, placedWidthPt: 72, placedHeightPt: 72 }));
    expect(of(findings, "image-resolution")).toEqual([]);
  });

  it("recomputes effective ppi after scale edits", async () => {
    const bytes = await imageFixture({ widthPx: 150, heightPx: 150, placedWidthPt: 72, placedHeightPt: 72 });
    const cases: [JobEdit[], number | null, string | null][] = [
      [[], null, null],
      [[{ kind: "scale", percent: 200 }], 75, "warn"],
      [[{ kind: "scale", percent: 400 }], 37.5, "error"],
      [[{ kind: "scale", percent: 200 }, { kind: "scale", percent: 50 }], null, null],
    ];
    for (const [edits, ppi, severity] of cases) {
      const findings = of(await inspect(bytes, { edits }), "image-resolution");
      if (ppi === null) {
        expect(findings, JSON.stringify(edits)).toEqual([]);
      } else {
        const finding = only(findings);
        expect(finding.data.ppi).toBeCloseTo(ppi, 9);
        expect(finding.severity).toBe(severity);
      }
    }
  });

  it("a fit-to-width edit is included in the final size", async () => {
    // 150 px over 1 in of art on a 2 in page; fitting the page to 4 in doubles every length.
    const bytes = await imageFixture({ widthPx: 150, heightPx: 150, placedWidthPt: 72, placedHeightPt: 72 });
    const edits: JobEdit[] = [{ kind: "scale", fit: { dimension: "width", targetMm: 4 * 25.4 } }];
    expect(only(of(await inspect(bytes, { edits }), "image-resolution")).data.ppi).toBeCloseTo(75, 6);
  });

  it.each(["form", "inline"] as const)("follows the CTM into a %s placement", async (placement) => {
    const findings = of(
      await inspect(await imageFixture({ widthPx: 72, heightPx: 72, placedWidthPt: 144, placedHeightPt: 144, placement })),
      "image-resolution",
    );
    expect(rules(findings)).toEqual([["below-error-threshold", "error"]]);
    const finding = only(findings);
    expect(finding.data.ppi).toBeCloseTo(36, 9);
    if (placement === "inline") expect(finding.message).toContain("inline image");
  });

  it("uses the lower axis for a non-uniformly scaled image", async () => {
    const finding = only(of(await inspect(await imageFixture({ widthPx: 200, heightPx: 60, placedWidthPt: 72, placedHeightPt: 72 })), "image-resolution"));
    expect(finding.severity).toBe("warn");
    expect(finding.data.ppiX).toBeCloseTo(200, 9);
    expect(finding.data.ppiY).toBeCloseTo(60, 9);
  });

  it("ignores an image cropped away by the job's edits", async () => {
    // The image sits at 36..108 pt; keep only the right-hand 30 pt of the 144 pt page.
    const bytes = await imageFixture({ widthPx: 10, heightPx: 10, placedWidthPt: 72, placedHeightPt: 72 });
    const crop: JobEdit = { kind: "crop", box: { xMm: (114 * 25.4) / 72, yMm: 0, widthMm: (30 * 25.4) / 72, heightMm: (144 * 25.4) / 72 } };
    expect(of(await inspect(bytes), "image-resolution")).toHaveLength(1);
    expect(of(await inspect(bytes, { edits: [crop] }), "image-resolution")).toEqual([]);
  });

  it("applies configured thresholds", async () => {
    const bytes = await imageFixture({ widthPx: 150, heightPx: 150, placedWidthPt: 72, placedHeightPt: 72 });
    const checks = { "image-resolution": { params: { warnBelowPpi: 300, errorBelowPpi: 200 } } };
    expect(rules(of(await inspect(bytes, {}, checks), "image-resolution"))).toEqual([["below-error-threshold", "error"]]);
  });
});

