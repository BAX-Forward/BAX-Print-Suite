describe("conformance", () => {
  it("a complete PDF/X-4 claim passes the structural check", async () => {
    const bytes = await pdfxFixture({ complete: true });
    expect(rules(of(await inspect(bytes), "conformance"))).toEqual([["claim", "info"]]);
    expect(await claims(bytes)).toEqual([{ family: "PDF/X", claim: "PDF/X-4", structural: "pass", missing: [] }]);
  });

  it("an incomplete PDF/X-4 claim is an error listing what is missing", async () => {
    const bytes = await pdfxFixture({ complete: false });
    expect(rules(of(await inspect(bytes), "conformance"))).toEqual([["claim-incomplete", "error"]]);
    const missing = (await claims(bytes))[0]?.missing.join("\n");
    expect(missing).toContain("OutputIntent of subtype GTS_PDFX");
    expect(missing).toContain("TrimBox or ArtBox on page(s) 1");
  });

  it("reads PDF/A claims from XMP", async () => {
    expect(await claims(await pdfaFixture({ complete: true }))).toEqual([{ family: "PDF/A", claim: "PDF/A-2b", structural: "pass", missing: [] }]);
    expect((await claims(await pdfaFixture({ complete: false })))[0]).toMatchObject({
      claim: "PDF/A-2",
      structural: "fail",
      missing: ["XMP pdfaid:conformance"],
    });
  });

  it("makes no claim for a plain file unless one is required", async () => {
    const bytes = await outlinedTextFixture();
    expect(of(await inspect(bytes), "conformance")).toEqual([]);
    expect(await claims(bytes)).toEqual([]);
    const required = of(await inspect(bytes, {}, { conformance: { params: { requireFamily: "PDF/X" } } }), "conformance");
    expect(rules(required)).toEqual([["required-claim-missing", "error"]]);
  });
});

describe("document", () => {
  it("an unreadable file is rejected with UnreadablePdfError", async () => {
    await expect(loadDocumentModel(new TextEncoder().encode("this is not a PDF"))).rejects.toBeInstanceOf(UnreadablePdfError);
  });

  it("an edit that does not fit the page is an error, and size checks skip that page", async () => {
    const bytes = await pageBoxesFixture({ mediaBox: [0, 0, 200, 200], trimBox: [0, 0, 200, 200] });
    const crop: JobEdit = { kind: "crop", box: { xMm: 50, yMm: 0, widthMm: 50, heightMm: 10 } };
    const findings = await inspect(bytes, { edits: [crop], printableWidthMm: 10 });
    expect(rules(of(findings, "document"))).toEqual([["edit-not-applicable", "error"]]);
    expect(only(of(findings, "document")).data.editIndex).toBe(0);
    expect(of(findings, "printable-width")).toEqual([]);
  });

  it("a well-formed file has no document findings", async () => {
    expect(of(await inspect(await pdfxFixture({ complete: true })), "document")).toEqual([]);
  });
});
